import { describe, expect, it } from 'vitest'
import { endCall, initialDemo, quoteHotel, sendMessage, startCall, transferCall } from '../services/demoEngine'

describe('deterministic demo flows', () => {
  it('keeps legal case details gated behind the sample identity', () => {
    const call = startCall(initialDemo('legal'))
    const requested = sendMessage(call, 'Dosyamın durumu nedir?', 'tr')
    expect(requested.record).toBeNull()
    expect(requested.messages.at(-1)?.key).toBe('flows.legalAsk')
    const verified = sendMessage(requested, 'DEMO-01', 'tr')
    expect(verified.record?.kind).toBe('case')
    expect(verified.steps).toContain('verify')
  })
  it('validates hotel dates, calculates a repeatable quote, and books only on request', () => {
    const call = startCall(initialDemo('hotel'))
    const now = new Date('2026-10-22T12:00:00')
    const invalid = quoteHotel(call, { checkin:'2026-10-20', checkout:'2026-10-22', guests:2, room:'standard' }, now)
    expect(invalid.messages.at(-1)?.key).toBe('flows.hotelInvalid')
    const quote = quoteHotel(call, { checkin:'2026-10-23', checkout:'2026-10-25', guests:2, room:'standard' }, now)
    expect(quote.hotelTotal).toBe(5636)
    expect(quote.record).toBeNull()
    const booked = sendMessage(quote, 'Rezervasyon yap', 'tr')
    expect(booked.record?.kind).toBe('reservation')
    expect(booked.record?.values.id).toBe('RSV-DEMO-1042')
  })
  it('does not create a lead until explicit consent', () => {
    const call = startCall(initialDemo('sales'))
    const offer = sendMessage(call, 'I need a plan for my team, budget 5000 TRY', 'en')
    expect(offer.record).toBeNull()
    const consent = sendMessage(offer, 'I would like an offer', 'en')
    expect(consent.record).toBeNull()
    expect(consent.messages.at(-1)?.key).toBe('flows.salesConsent')
    const declined = sendMessage(consent, 'no', 'en')
    expect(declined.record).toBeNull()
    const accepted = sendMessage(consent, 'I consent', 'en')
    expect(accepted.record?.kind).toBe('lead')
    expect(accepted.record?.values.consent).toBe('✓')
  })
  it('tracks sample orders and handles unknown numbers', () => {
    const call = startCall(initialDemo('commerce'))
    const prompted = sendMessage(call, 'Kargom nerede?', 'tr')
    expect(prompted.messages.at(-1)?.key).toBe('flows.commerceAsk')
    const unknown = sendMessage(prompted, 'ORD-9999', 'tr')
    expect(unknown.messages.at(-1)?.key).toBe('flows.commerceInvalid')
    const found = sendMessage(prompted, 'ORD-1003', 'tr')
    expect(found.record?.timeline).toEqual(['statusPreparing','statusShipped','statusOut','statusDelivered'])
  })
  it('simulates handoff and preserves a summary after the call', () => {
    const call = sendMessage(startCall(initialDemo('commerce')), 'ORD-1002', 'en')
    const transferred = transferCall(call)
    expect(transferred.status).toBe('transferred_demo')
    expect(transferred.intent).toBe('order')
    expect(transferred.record?.values.id).toBe('ORD-1002')
    expect(transferred.steps).toContain('transfer')
    expect(endCall(transferred).status).toBe('ended')
    expect(startCall(transferred).record).toBeNull()
  })
})
